/**
 * Renders docs/steam/STEAMWORKS_CONFIG.md: the exact achievements, stats,
 * leaderboards and Rich Presence tokens to enter in Steamworks, read from
 * the code that uses them so the partner portal and the game cannot drift.
 *
 *   npx tsx scripts/steam/steamworks-sheet.ts          # rewrite the file
 *   npx tsx scripts/steam/steamworks-sheet.ts --check  # fail when stale
 */

import fs from "fs"
import path from "path"
import { ACHIEVEMENTS } from "../../engine/steam-service"

const root = path.join(__dirname, "..", "..")
export const SHEET_PATH = path.join(root, "docs", "steam", "STEAMWORKS_CONFIG.md")

/** Lower is better only for the weeks-to-S-tier board. */
const ASCENDING_LEADERBOARDS = new Set(["lead_fastest_stier"])

const LEADERBOARD_LABELS: Record<string, string> = {
    lead_world_ranking: "Peak Elo rating",
    lead_major_wins: "Major wins",
    lead_fastest_stier: "Fastest rise to S-Tier (career weeks)",
    lead_total_earnings: "Career income",
    lead_win_streak: "Longest win streak",
    lead_tournaments_won: "Titles won",
}

function allowlist(source: string, name: string): string[] {
    const match = source.match(new RegExp(`const ${name} = new Set\\(\\[([\\s\\S]*?)\\]\\)`))
    if (!match) throw new Error(`${name} not found in electron/steam.js`)
    return [...match[1].matchAll(/'([A-Za-z0-9_]+)'/g)].map(m => m[1])
}

export function steamAllowlists(): { achievements: string[]; stats: string[]; leaderboards: string[] } {
    const source = fs.readFileSync(path.join(root, "electron", "steam.js"), "utf8")
    return {
        achievements: allowlist(source, "ALLOWED_ACHIEVEMENTS"),
        stats: allowlist(source, "ALLOWED_STATS"),
        leaderboards: allowlist(source, "ALLOWED_LEADERBOARDS"),
    }
}

/** Allowed by the desktop process but never fed a value by the game yet. */
const RESERVED_STATS = new Set(["stat_players_developed"])

function richPresenceFiles(): Array<{ file: string; text: string }> {
    const dir = path.join(root, "steamworks", "rich-presence")
    return fs.readdirSync(dir).filter(file => file.endsWith(".vdf")).sort()
        .map(file => ({ file, text: fs.readFileSync(path.join(dir, file), "utf8").trimEnd() }))
}

const cell = (text: string) => text.replace(/\|/g, "\\|")

export function renderSteamworksSheet(): string {
    const { stats, leaderboards } = steamAllowlists()
    const lines: string[] = [
        "# Steamworks configuration: Esports Manager: FPS (App 4326170)",
        "",
        "Generated by `npx tsx scripts/steam/steamworks-sheet.ts` from `engine/steam-service.ts`, `electron/steam.js` and `steamworks/rich-presence/`. Do not edit by hand; `__tests__/steamworks-sheet.test.ts` fails when this file is stale.",
        "",
        "Enter each value exactly (API names are case-sensitive), then publish under **Publish → Prepare for publishing**. Stats and achievements only work in the client after that publish.",
        "",
        "## Achievements",
        "",
        "Steamworks → Stats & Achievements → Achievements. Display name and description must match the in-game text below. Icons: 256×256 JPG/PNG, an unlocked and a grey locked version per achievement.",
        "",
        "| # | API name | Display name | Description | Hidden |",
        "|---|---|---|---|---|",
    ]
    Object.values(ACHIEVEMENTS).forEach((a, i) => {
        lines.push(`| ${i + 1} | \`${a.id}\` | ${cell(a.name)} | ${cell(a.description)} | ${a.hidden ? "Yes" : "No"} |`)
    })
    lines.push(
        "",
        "## Stats",
        "",
        "Steamworks → Stats & Achievements → Stats. Type **INT**, Set by **Client**, Increment only **off** (the desktop process keeps best-career values itself), default 0.",
        "",
        "| API name | Written by the game today |",
        "|---|---|",
        ...stats.map(name => `| \`${name}\` | ${RESERVED_STATS.has(name) ? "No: reserved, safe to leave out of Steamworks" : "Yes"} |`),
        "",
        "## Leaderboards",
        "",
        "Steamworks → Stats & Achievements → Leaderboards. Display type **Numeric**, community name and sort method as below.",
        "",
        "| API name | Community name | Sort |",
        "|---|---|---|",
        ...leaderboards.map(name => `| \`${name}\` | ${LEADERBOARD_LABELS[name] ?? name} | ${ASCENDING_LEADERBOARDS.has(name) ? "Ascending (lower is better)" : "Descending"} |`),
        "",
        "## Rich Presence",
        "",
        "Steamworks → Community → Rich Presence: upload each file below (one per language). The game sets `team`, `season`, `week`, `rank` and then `steam_display`; without these files Steam shows only the game name.",
        "",
    )
    for (const { file, text } of richPresenceFiles()) {
        lines.push(`### ${file}`, "", "```vdf", text, "```", "")
    }
    return lines.join("\n").trimEnd() + "\n"
}

if (require.main === module) {
    const sheet = renderSteamworksSheet()
    if (process.argv.includes("--check")) {
        const current = fs.existsSync(SHEET_PATH) ? fs.readFileSync(SHEET_PATH, "utf8") : ""
        if (current !== sheet) {
            console.error("docs/steam/STEAMWORKS_CONFIG.md is stale: run npx tsx scripts/steam/steamworks-sheet.ts")
            process.exit(1)
        }
        console.log("Steamworks sheet is up to date.")
    } else {
        fs.mkdirSync(path.dirname(SHEET_PATH), { recursive: true })
        fs.writeFileSync(SHEET_PATH, sheet)
        console.log(`Wrote ${path.relative(root, SHEET_PATH)}`)
    }
}
